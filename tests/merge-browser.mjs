import {chromium,expect} from '../frontend/node_modules/@playwright/test/index.mjs';
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const fixture=JSON.parse(await readFile('/tmp/wiavoice-auth-fixture.json','utf8'));
const origin='https://axforwork.wia.co.kr';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const context=await browser.newContext({viewport:{width:1600,height:1100}});const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 async function login(){assert.equal((await context.request.post(origin+'/api/auth/login',{headers:{Origin:origin,'X-AX-Request':'1'},data:{employee_id:fixture.employee_id,password:fixture.password}})).status(),200);}
 await login();await page.goto(origin+'/wiavoice/#my-voice');
 await page.getByRole('button',{name:'Voice 병합',exact:true}).click();
 const popup=page.getByRole('dialog');await expect(popup).toBeVisible();
 await expect(popup.getByRole('button',{name:'병합',exact:true})).toBeDisabled();
 for(const name of ['서비스 인사','서비스 안내','마무리 인사'])await popup.locator('.merge-choice').filter({hasText:name}).click();
 await popup.getByRole('button',{name:'마무리 인사 위로',exact:true}).click();
 await popup.getByRole('button',{name:'마무리 인사 위로',exact:true}).click();
 await expect(popup.locator('.merge-track b')).toHaveText(['마무리 인사','서비스 인사','서비스 안내']);
 await popup.getByLabel('공백 일괄 적용',{exact:true}).fill('0.8');await popup.getByRole('button',{name:'적용',exact:true}).click();
 await expect(popup.getByLabel('1번째 공백 (초)',{exact:true})).toHaveValue('0.8');
 await popup.getByLabel('1번째 공백 (초)',{exact:true}).fill('1.2');await popup.getByLabel('2번째 공백 (초)',{exact:true}).fill('0.6');
 await popup.screenshot({path:'test-results/merge-sequence.png'});
 await popup.getByRole('button',{name:'병합',exact:true}).click();
 await expect(page.getByRole('heading',{name:'병합한 Voice의 이름',exact:true})).toBeVisible();
 await expect(popup.getByLabel('음성 이름',{exact:true})).toBeFocused();
 await popup.getByLabel('음성 이름',{exact:true}).fill('전체 서비스 소개 · 병합');
 await popup.screenshot({path:'test-results/merge-name.png'});
 await popup.getByRole('button',{name:'병합하고 저장',exact:true}).click();
 await expect(popup).toHaveCount(0);
 await expect(page.getByRole('heading',{name:'전체 서비스 소개 · 병합',exact:true})).toBeVisible({timeout:45000});
 const actions=await (await context.request.get(origin+'/wiavoice/api/merge-actions')).json();const action=actions[0];
 assert.equal(action.status,'completed');assert.deepEqual(action.gaps_seconds,[1.2,.6]);
 assert.deepEqual(action.input_voices.map(v=>v.name),['마무리 인사','서비스 인사','서비스 안내']);
 const voices=await (await context.request.get(origin+'/wiavoice/api/my-voices')).json();const output=voices.items.find(v=>v.voice_id===action.result_voice_id);
 assert.equal(output.text,'3번째 테스트 음성입니다.\n\n1번째 테스트 음성입니다.\n\n2번째 테스트 음성입니다.');
 assert.equal(output.model,'merged');assert.equal(output.sample_rate,48000);
 assert.equal((await context.request.get(origin+output.audio_url+'?download=true')).status(),200);
 const card=page.locator('.library-card').filter({hasText:'전체 서비스 소개 · 병합'});
 await card.locator('audio').evaluate(a=>a.play());await expect.poll(()=>card.locator('audio').evaluate(a=>a.currentTime)).toBeGreaterThan(0);
 await page.screenshot({path:'test-results/merge-completed.png',fullPage:true});
 await page.setViewportSize({width:1200,height:900});assert(await page.evaluate(()=>document.documentElement.scrollWidth<=1200));
 await page.getByRole('button',{name:'로그아웃',exact:true}).click();await page.waitForURL('**/login?next=**');
 await login();await page.goto(origin+'/wiavoice/#my-voice');
 await expect(page.getByRole('heading',{name:'전체 서비스 소개 · 병합',exact:true})).toBeVisible();
 assert.equal((await context.request.get(origin+output.audio_url)).status(),200);
 await writeFile('/tmp/wiavoice-merge-result.json',JSON.stringify({action_id:action.action_id,voice_id:output.voice_id,user_id:fixture.user_id}));
 await context.request.post(origin+'/wiavoice/api/auth/logout',{headers:{Origin:origin}});
 assert.deepEqual(errors,[]);
 console.log('Selection, reorder, per-gap silence, naming, queued merge, metadata, playback and re-login persistence verified');
}finally{await browser.close();}
