import {chromium,expect} from '../frontend/node_modules/@playwright/test/index.mjs';
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const fixture=JSON.parse(await readFile('/tmp/wiavoice-auth-fixture.json','utf8'));
const origin='https://axforwork.wia.co.kr';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const context=await browser.newContext({viewport:{width:1600,height:1100}});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 async function login(){const r=await context.request.post(origin+'/api/auth/login',{headers:{Origin:origin,'X-AX-Request':'1'},data:{employee_id:fixture.employee_id,password:fixture.password}});assert.equal(r.status(),200);}
 await login();await page.goto(origin+'/wiavoice/');
 await page.getByRole('button',{name:'My Voice',exact:true}).click();
 await expect(page.getByText('나만의 목소리를 모아 보세요')).toBeVisible();
 await page.getByRole('button',{name:'Voice 생성',exact:true}).click();
 await page.getByLabel('읽을 문장').fill('안녕하세요. 저장한 목소리는 언제든 다시 들을 수 있습니다.');
 await page.getByRole('button',{name:'Voice 생성하기',exact:true}).click();
 console.log('Live Qwen generation requested');
 await expect(page.locator('.action-save')).toBeVisible({timeout:300000});
 const download=await page.locator('.action-download').boundingBox(),save=await page.locator('.action-save').boundingBox();
 assert(Math.abs(download.y-save.y)<2&&download.x<save.x);
 await page.locator('.result-panel').screenshot({path:'test-results/my-voice-actions.png'});
 await page.locator('.action-save').click();
 await expect(page.getByRole('dialog')).toBeVisible();await expect(page.getByLabel('음성 이름')).toBeFocused();
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.locator('.action-save').click();
 await page.getByLabel('음성 이름').fill('서비스 소개 · 차분한 목소리');
 await page.getByRole('dialog').screenshot({path:'test-results/my-voice-save-dialog.png'});
 await page.getByRole('dialog').getByRole('button',{name:'My Voice 저장',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('.action-save')).toBeDisabled();
 await page.getByRole('button',{name:'보러 가기'}).click();
 await expect(page.locator('.library-card')).toHaveCount(1);
 await expect(page.getByRole('heading',{name:'서비스 소개 · 차분한 목소리',exact:true})).toBeVisible();
 const response=await context.request.get(origin+'/wiavoice/api/my-voices');const data=await response.json();
 const voice=data.items[0];assert.equal(data.total,1);
 const audio=await context.request.get(origin+voice.audio_url+'?download=true');assert.equal(audio.status(),200);
 const bytes=await audio.body();assert.equal(bytes.subarray(0,4).toString(),'RIFF');
 await page.locator('.library-card audio').evaluate(a=>a.play());
 await expect.poll(()=>page.locator('.library-card audio').evaluate(a=>a.currentTime)).toBeGreaterThan(0);
 await page.screenshot({path:'test-results/my-voice-library.png',fullPage:true});
 await page.getByLabel('저장한 음성 검색').fill('없는 결과');await page.getByRole('button',{name:'검색',exact:true}).click();
 await expect(page.getByText('검색한 음성이 없습니다')).toBeVisible();
 await page.getByRole('button',{name:'로그아웃',exact:true}).click();await page.waitForURL('**/login?next=**');
 await login();await page.goto(origin+'/wiavoice/#my-voice');
 await expect(page.locator('.library-card')).toHaveCount(1);
 assert.deepEqual(await (await context.request.get(origin+'/wiavoice/api/jobs')).json(),[]);
 assert.equal((await context.request.get(origin+voice.audio_url)).status(),200);
 await page.setViewportSize({width:1200,height:900});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=1200));
 await page.getByRole('button',{name:'로그아웃',exact:true}).click();await page.waitForURL('**/login?next=**');
 await writeFile('/tmp/wiavoice-library-result.json',JSON.stringify({user_id:fixture.user_id,voice_id:voice.voice_id,sha256:createHash('sha256').update(bytes).digest('hex')}));
 assert.deepEqual(errors,[]);
 console.log('Two-column actions, dialog, save, search, playback/download and persistence after logout verified');
}finally{await browser.close();}
